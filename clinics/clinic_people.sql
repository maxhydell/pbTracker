-- PBTRKR Clinics shared participant roster.
-- Run in the Supabase SQL editor for project qyhzxfserrvsgutfhyel.
-- Past event pages use this active roster when rendering participants.

create table if not exists public.clinic_people (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(btrim(name)) between 2 and 120),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists clinic_people_active_name_idx
  on public.clinic_people (lower(btrim(name)))
  where is_active;

create or replace function public.set_clinic_person_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists clinic_people_set_updated_at on public.clinic_people;
create trigger clinic_people_set_updated_at
  before update on public.clinic_people
  for each row execute function public.set_clinic_person_updated_at();

alter table public.clinic_people enable row level security;

drop policy if exists "Anyone can read active clinic people" on public.clinic_people;
create policy "Anyone can read active clinic people"
  on public.clinic_people
  for select
  to anon, authenticated
  using (is_active);

drop policy if exists "Clinic admins can read all clinic people" on public.clinic_people;
create policy "Clinic admins can read all clinic people"
  on public.clinic_people
  for select
  to authenticated
  using (lower(btrim(coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), ''))) in ('clinic_admin', 'pbtrkr_admin'));

drop policy if exists "Clinic admins can manage clinic people" on public.clinic_people;
create policy "Clinic admins can manage clinic people"
  on public.clinic_people
  for all
  to authenticated
  using (lower(btrim(coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), ''))) in ('clinic_admin', 'pbtrkr_admin'))
  with check (lower(btrim(coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), ''))) in ('clinic_admin', 'pbtrkr_admin'));

grant select on public.clinic_people to anon, authenticated;
grant insert, update, delete on public.clinic_people to authenticated;

